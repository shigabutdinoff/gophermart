package apiconfig

// MaxBodyBytes задаёт операции границу тела запроса.
// huma отвечает 413, прочитав лишний байт сверх границы, поэтому предел
// операции на байт больше разрешённого размера тела.
func MaxBodyBytes(limit int64) int64 {
	return limit + 1
}

// RouterLimit задаёт маршрутизатору границу читаемого потока.
// Она с запасом больше предела операции, иначе в границу первой упрётся
// маршрутизатор и чужая ошибка чтения станет 500 вместо 413.
func RouterLimit(limit int64) int64 {
	return MaxBodyBytes(limit) + 1
}
